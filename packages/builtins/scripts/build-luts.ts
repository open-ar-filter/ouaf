/**
 * Generates the built-in LUTs (`assets/luts/*.cube`): our own color grades, defined as functions below and sampled on
 * a 17³ grid. Dedicated to the public domain (CC0-1.0).
 *
 *   npm run build:luts -w @ouaf/builtins
 *
 * The grades work on gamma-encoded sRGB values (display-referred), which is what a `.cube` file applied to camera
 * video expects: input and output in [0, 1]. They are smooth (no hard clipping), so a 17-point grid sampled with
 * trilinear filtering stays within about two 8-bit steps of the exact grade at worst and a third of a step on average
 * (checked by the tests), at an eighth of the size of a 33³ LUT.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export type Rgb = [number, number, number]
export type Grade = (r: number, g: number, b: number) => Rgb

export const LUT_SIZE = 17

const clamp01 = (x: number) => (x < 0 ? 0 : x > 1 ? 1 : x)
/** Rec. 709 luma of gamma-encoded values. */
const luma = (r: number, g: number, b: number) => 0.2126 * r + 0.7152 * g + 0.0722 * b
const mix = (a: number, b: number, t: number) => a + (b - a) * t

/** Contrast S-curve through (0, 0), (0.5, 0.5) and (1, 1): a logistic curve of steepness k, rescaled. */
function sCurve(x: number, k: number): number {
  const s = (t: number) => 1 / (1 + Math.exp(-k * (t - 0.5)))
  const lo = s(0)
  return (s(x) - lo) / (s(1) - lo)
}

/** Scales the saturation around the luma (1 = unchanged, 0 = grey). */
function saturate(r: number, g: number, b: number, amount: number): Rgb {
  const y = luma(r, g, b)
  return [mix(y, r, amount), mix(y, g, amount), mix(y, b, amount)]
}

/**
 * Boosts the saturation without clipping: each channel's distance to the luma is scaled, then compressed smoothly
 * (tanh) into the room left before 0 or 1. A hard clamp would put kinks in the grade that a coarse LUT cannot follow.
 */
function boost(r: number, g: number, b: number, amount: number): Rgb {
  const y = luma(r, g, b)
  const soft = (c: number) => {
    const d = (c - y) * amount
    const room = d > 0 ? 1 - y : y
    return room < 1e-6 ? y : y + room * Math.tanh(d / room)
  }
  return [soft(r), soft(g), soft(b)]
}

export const GRADES: Record<string, { title: string; grade: Grade }> = {
  vintage: {
    title: 'Faded warm tones',
    grade: (r, g, b) => {
      // Softer contrast, muted colors, warm cast, then lifted blacks and dimmed whites (faded print).
      const [sr, sg, sb] = saturate(sCurve(r, 3), sCurve(g, 3), sCurve(b, 3), 0.7)
      return [0.07 + 0.88 * clamp01(sr) ** 0.92, 0.06 + 0.87 * clamp01(sg) ** 0.98, 0.08 + 0.78 * clamp01(sb) ** 1.12]
    },
  },
  noir: {
    title: 'High-contrast black and white',
    grade: (r, g, b) => {
      const y = sCurve(luma(r, g, b), 6)
      return [y, y, y]
    },
  },
  warm: {
    title: 'Warms the image',
    // Per-channel gamma: shifts the white balance towards amber while keeping black and white in place.
    grade: (r, g, b) => [r ** 0.88, g ** 0.97, b ** 1.18],
  },
  cool: {
    title: 'Cools the image',
    grade: (r, g, b) => [r ** 1.15, g ** 1.0, b ** 0.88],
  },
  vivid: {
    title: 'Saturated colors',
    grade: (r, g, b) => boost(sCurve(r, 4), sCurve(g, 4), sCurve(b, 4), 1.6),
  },
}

/** Samples a grade on a size³ grid, red varying fastest (the `.cube` order), clamped to [0, 1]. */
export function sampleLut(grade: Grade, size = LUT_SIZE): Float64Array {
  const out = new Float64Array(size * size * size * 3)
  let i = 0
  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const rgb = grade(r / (size - 1), g / (size - 1), b / (size - 1))
        for (const c of rgb) out[i++] = clamp01(c)
      }
    }
  }
  return out
}

const num = (x: number) => x.toFixed(5).replace(/\.?0+$/, '') || '0'

/** The `.cube` text of a built-in LUT (Adobe/Resolve Cube LUT Specification 1.0). */
export function cubeFile(name: string, size = LUT_SIZE): string {
  const def = GRADES[name]
  if (!def) throw new Error(`Unknown LUT "${name}"`)
  const data = sampleLut(def.grade, size)
  const lines = [
    `TITLE "Ouaf ${name}"`,
    `# ${def.title}. Generated by packages/builtins/scripts/build-luts.ts; CC0-1.0 (public domain).`,
    '# Input and output: gamma-encoded sRGB.',
    `LUT_3D_SIZE ${size}`,
    'DOMAIN_MIN 0 0 0',
    'DOMAIN_MAX 1 1 1',
  ]
  for (let i = 0; i < data.length; i += 3) lines.push(`${num(data[i]!)} ${num(data[i + 1]!)} ${num(data[i + 2]!)}`)
  return lines.join('\n') + '\n'
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL('../assets/luts/', import.meta.url)
  for (const name of Object.keys(GRADES)) {
    const file = new URL(`${name}.cube`, dir)
    writeFileSync(file, cubeFile(name))
    console.log(fileURLToPath(file))
  }
}
