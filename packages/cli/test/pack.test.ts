const fixtures = join(import.meta.dirname, 'fixtures')
const authoring = join(fixtures, 'authoring')
const dec = new TextDecoder()

const temps: string[] = []
async function temp(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), 'ouaf-pack-'))
  temps.push(dir)
  return dir
}
afterEach(async () => {
  await Promise.all(temps.splice(0).map((d) => rm(d, { recursive: true, force: true })))
})

/** A filter folder with `filter.js` (or another entry) and extra files. */
async function folder(files: Record<string, string | Uint8Array>): Promise<string> {
  const dir = join(await temp(), 'filter')
  for (const [path, content] of Object.entries(files)) {
    await mkdir(join(dir, path, '..'), { recursive: true })
    await writeFile(join(dir, path), content)
  }
  await mkdir(dir, { recursive: true })
  return dir
}

const data = `id: 'x', name: 'X', version: '1.0.0', license: 'CC0-1.0', requires: {}`
const filterJs = (rest = `layers: []`) => `export default { ${data}, ${rest} }\n`

async function cli(...argv: string[]) {
  const out: string[] = []
  const err: string[] = []
  const code = await run(argv, { out: (t) => out.push(t), err: (t) => err.push(t) })
  return { code, out: out.join('\n'), err: err.join('\n') }
}

function unzip(zip: Uint8Array): Record<string, string> {
  return Object.fromEntries(readZipEntries(zip).map((e) => [e.name, dec.decode(readZipEntry(zip, e))]))
}

/** Runs a script definition in the script runtime of @ouaf/core, as the engine's sandbox Worker does. */
async function runScript(load: () => Promise<{ default?: unknown }>): Promise<WireDone[]> {
  const scope = fakeScope()
  scriptRuntime(scope, { harden: false, load })
  const channel = new MessageChannel()
  scope.send({ t: 'port' }, [channel.port2])
  const conn = { port: channel.port1 as unknown as Parameters<typeof ask>[0]['port'] }
  const face = { id: 1, index: 0, pose: { yaw: 0, pitch: 0, roll: 0 }, size: 0.2 }
  const answers = [
    await ask(conn, init('', { layers: ['label', ''] })),
    await ask(conn, frame(1, { faces: [face], events: [{ name: 'smile', face: 1 }] })),
    await ask(conn, frame(2, { faces: [face], events: [{ name: 'smile', face: 1 }] })),
    await ask(conn, frame(3, { events: [{ name: 'message:reset', payload: { data: null } }] })),
  ]
  channel.port1.close()
  return answers
}

describe('ouaf pack: filter.ts → .ouaf', () => {
  it('splits data and functions: manifest.json with "ouaf" and "script", script.js, assets/', async () => {
    const result = await packFolder(authoring)
    expect(result.report.errors).toEqual([])
    expect(result.report.ok).toBe(true)
    expect(result.entry).toBe('filter.ts')
    expect(result.files).toEqual(['manifest.json', 'script.js', 'assets/star.png'])
    const files = unzip(result.zip!)
    expect(Object.keys(files)).toEqual(result.files)
    const manifest = JSON.parse(files['manifest.json']!) as Record<string, unknown>
    expect(Object.keys(manifest)[0]).toBe('ouaf')
    expect(manifest.ouaf).toBe('1')
    expect(manifest.script).toEqual({ entry: 'script.js', setup: true, on: ['smile', 'message:reset'], uses: ['face.pose'] })
    for (const key of ['state', 'setup', 'update', 'on', 'draw']) expect(manifest).not.toHaveProperty(key)
    expect(manifest.layers).toHaveLength(2)
    // script.js is self-contained: no import, and @ouaf/spec reduced to the identity function.
    expect(files['script.js']).not.toMatch(/^\s*import\b/m)
    expect(files['script.js']).not.toContain('typebox')
    expect(files['script.js']).toMatch(/^\/\/ Generated by ouaf pack from filter\.ts/)
  })

  it('round trip: the package validates, and its script.js behaves as filter.ts in the script runtime', async () => {
    const result = await packFolder(authoring)
    const report = await validatePackage(zipSource(result.zip!, 'smile-counter.ouaf'))
    expect(report.errors).toEqual([])
    expect(report.warnings).toEqual([])

    const dir = await temp()
    await writeFile(join(dir, 'script.mjs'), unzip(result.zip!)['script.js']!)
    const packed = await runScript(() => import(pathToFileURL(join(dir, 'script.mjs')).href) as Promise<{ default?: unknown }>)
    // Dev mode: the source module itself.
    const dev = await runScript(() => import(pathToFileURL(join(authoring, 'filter.ts')).href) as Promise<{ default?: unknown }>)
    expect(packed).toEqual(dev)
    expect(packed[0]!.emits).toEqual([['ready', { random: expect.any(Number) }]])
    expect(packed[1]!.commands).toEqual([['set', 0, 1, { text: '😄 × 1' }]])
    expect(packed[2]!.emits).toEqual([['smiles', 2]])
    expect(packed[3]!.commands).toEqual([['set', 0, null, { text: null }]])
  })

  it('is deterministic: the same folder gives the same bytes, whatever the file times', async () => {
    const a = await packFolder(authoring)
    const copy = join(await temp(), 'copy')
    await cp(authoring, copy, { recursive: true })
    await utimes(join(copy, 'assets', 'star.png'), new Date('2001-02-03'), new Date('2001-02-03'))
    const b = await packFolder(copy)
    expect(Buffer.from(b.zip!).equals(Buffer.from(a.zip!))).toBe(true)
    for (const e of readZipEntries(a.zip!)) expect(e.unixMode).toBe(0o100000)
  })

  it('inlines dynamic imports: script.js stays one file without import', async () => {
    const dir = await folder({
      'filter.js': `${filterJs()}`.replace('layers: []', `layers: [], setup() { void import('./later.js').then((m) => m.x) }`),
      'later.js': `export const x = 1\n`,
    })
    const result = await packFolder(dir)
    expect(result.report.errors).toEqual([])
    expect(result.files).toEqual(['manifest.json', 'script.js'])
    expect(unzip(result.zip!)['script.js']).not.toMatch(/\bimport\s*[('"]/)
  })

  it('a data-only filter has no script section and no script.js', async () => {
    const dir = await folder({ 'filter.js': filterJs(`layers: [{ type: 'color', saturation: 0 }], state: { n: 1 }`) })
    const result = await packFolder(dir)
    expect(result.report.errors).toEqual([])
    expect(result.files).toEqual(['manifest.json'])
    expect(JSON.parse(unzip(result.zip!)['manifest.json']!)).not.toHaveProperty('script')
  })

  it('reports what manifest.json cannot hold, with the JSON pointer', async () => {
    const dir = await folder({
      'filter.js': filterJs(`layers: [{ type: 'text', text: () => 'hi', anchor: 'screen', size: [1, undefined] }],
        description: new Date(0), tags: [NaN], script: { entry: 'other.js', uses: ['face.pose'] }, update: 3, on: { smile: 'nope' }`),
    })
    const { report, zip } = await packFolder(dir)
    expect(zip).toBeUndefined()
    const errors = report.errors.map((e) => [e.code, e.path, e.file])
    expect(errors).toEqual(expect.arrayContaining([
      ['function-in-data', '/layers/0/text', 'filter.js'],
      ['not-json', '/layers/0/size', 'filter.js'],
      ['not-json', '/description', 'filter.js'],
      ['not-json', '/tags/0', 'filter.js'],
      ['script-section', '/script/entry', 'filter.js'],
      ['not-a-function', '/update', 'filter.js'],
      ['not-a-function', '/on/smile', 'filter.js'],
    ]))
  })

  it('refuses getters in the data without calling them (they would run after the time limit)', async () => {
    const dir = await folder({
      'filter.js': `export default { ${data}, get description() { for (;;) {} }, layers: [{ type: 'text', get text() { for (;;) {} } }] }\n`,
    })
    const { report, zip } = await packFolder(dir)
    expect(zip).toBeUndefined()
    expect(report.errors.map((e) => [e.code, e.path])).toEqual([['accessor-in-data', '/description']])
    const nested = await packFolder(await folder({ 'filter.js': filterJs(`layers: [{ type: 'text', get text() { for (;;) {} } }]`) }))
    expect(nested.report.errors.map((e) => [e.code, e.path])).toEqual([['accessor-in-data', '/layers/0/text']])
  })

  it('reports validation issues against filter.js (by JSON pointer: manifest.json is generated)', async () => {
    const dir = await folder({ 'filter.js': filterJs(`layers: [{ type: 'text', text: 'hi', anchor: 'forehaed' }], on: { smile() {} }`) })
    const { report } = await packFolder(dir)
    const issue = report.errors.find((e) => e.code === 'unknown-anchor')
    expect(issue).toMatchObject({ file: 'filter.js', path: '/layers/0/anchor' })
    expect(issue).not.toHaveProperty('line')
  })

  it('reports build errors with their location: syntax, Node built-ins, a missing import', async () => {
    const syntax = await packFolder(await folder({ 'filter.js': `export default {\n  id: 'x',,\n}\n` }))
    expect(syntax.report.errors[0]).toMatchObject({ code: 'build-error', file: 'filter.js', line: 2 })
    // A plain message (no terminal colors, no "[CODE]"), reported once although the bundle is generated twice.
    expect(syntax.report.errors[0]!.message).toBe('Unexpected token')
    const node = await packFolder(await folder({ 'filter.js': `import { readFileSync } from 'node:fs'\n${filterJs()}` }))
    expect(node.report.errors).toEqual([expect.objectContaining({ code: 'build-error', file: 'filter.js', line: 1 })])
    expect(node.report.errors[0]!.message).toBe(`Could not resolve 'node:fs' in filter.js`)
    const missing = await packFolder(await folder({ 'filter.js': `import { x } from './nope.js'\n${filterJs()}` }))
    expect(missing.report.errors[0]!.message).toContain('./nope.js')
    const spec = await packFolder(await folder({ 'filter.js': `import { validateManifest } from '@ouaf/spec'\n${filterJs()}` }))
    expect(spec.report.errors[0]!.code).toBe('build-error')
  })

  it('runs filter.js without Node APIs and with a time limit', async () => {
    const proc = await packFolder(await folder({ 'filter.js': `export default { ${data}, layers: [], cwd: process.cwd() }\n` }))
    expect(proc.report.errors[0]).toMatchObject({ code: 'run-error' })
    expect(proc.report.errors[0]!.message).toContain('process is not defined')
    const loop = await packFolder(await folder({ 'filter.js': `for (;;) {}\n${filterJs()}` }))
    expect(loop.report.errors[0]!.message).toMatch(/did not finish within \d+ ms/)
    const none = await packFolder(await folder({ 'filter.js': `export const x = 1\n` }))
    expect(none.report.errors[0]!.code).toBe('no-default-export')
    const logs = await packFolder(await folder({ 'filter.js': `console.log('hello')\n${filterJs()}` }))
    expect(logs.report.warnings.map((w) => w.code)).toContain('console')
  }, 10_000)

  it('throws PackSourceError when there is nothing to pack', async () => {
    await expect(packFolder(join(fixtures, 'nope'))).rejects.toBeInstanceOf(PackSourceError)
    await expect(packFolder(await folder({ 'README.md': 'hi' }))).rejects.toThrow(/no filter\.ts, filter\.js or manifest\.json/)
    await expect(packFolder(await folder({ 'filter.js': '', 'filter.ts': '' }))).rejects.toThrow(/both filter\.ts and filter\.js/)
    await expect(packFolder(await folder({ 'filter.js': '', 'manifest.json': '{}' }))).rejects.toThrow(/both filter\.js and manifest\.json/)
  })
})

describe('ouaf pack: folder contents', () => {
  it('packs a manifest.json folder as it is', async () => {
    const result = await packFolder(join(fixtures, 'valid'))
    expect(result.report.errors).toEqual([])
    expect(result.entry).toBeUndefined()
    expect(result.files[0]).toBe('manifest.json')
    expect(result.files.every((f) => f === 'manifest.json' || f.startsWith('assets/'))).toBe(true)
  })

  it('leaves out hidden files and files outside the layout', async () => {
    const dir = await folder({
      'filter.js': filterJs(),
      'README.md': 'notes',
      'src/util.js': 'export {}',
      'script.js': 'stale, ignored: written from filter.js',
      'assets/.DS_Store': 'x',
      'assets/.cache/a.png': 'x',
      '.git/config': 'x',
    })
    const result = await packFolder(dir)
    expect(result.files).toEqual(['manifest.json'])
    expect(result.hidden).toEqual(['assets/.DS_Store', 'assets/.cache/'])
  })

  it('refuses symbolic links in assets/, without reading what they point to', async () => {
    const outside = await temp()
    await writeFile(join(outside, 'secret.png'), 'secret')
    const dir = await folder({ 'filter.js': filterJs(), 'assets/ok.png': 'x' })
    await symlink(join(outside, 'secret.png'), join(dir, 'assets', 'leak.png'))
    await symlink(outside, join(dir, 'assets', 'more'))
    const result = await packFolder(dir)
    expect(result.zip).toBeUndefined()
    expect(result.report.errors.filter((e) => e.code === 'symlink').map((e) => e.file).sort()).toEqual(['assets/leak.png', 'assets/more'])
    expect(result.files).not.toContain('assets/leak.png')

    const linked = await folder({ 'filter.js': filterJs() })
    await symlink(outside, join(linked, 'assets'))
    expect((await packFolder(linked)).report.errors.map((e) => [e.code, e.file])).toEqual([['symlink', 'assets']])
  })

  it('refuses a linked manifest.json in a manifest folder', async () => {
    const outside = await temp()
    await writeFile(join(outside, 'm.json'), '{}')
    const dir = await folder({})
    await symlink(join(outside, 'm.json'), join(dir, 'manifest.json'))
    expect((await packFolder(dir)).report.errors.map((e) => e.code)).toEqual(['symlink'])
  })
})

describe('writeZip', () => {
  it('writes an archive the reader reads back: deflated or stored, UTF-8 names, regular files', () => {
    const enc = new TextEncoder()
    const random = Uint8Array.from({ length: 256 }, (_, i) => (i * 7919 + 13) % 251)
    const zip = writeZip([
      { path: 'manifest.json', data: enc.encode('{"a":1}'.repeat(50)) },
      { path: 'assets/été.png', data: random },
      { path: 'assets/empty.txt', data: new Uint8Array() },
    ])
    const entries = readZipEntries(zip)
    expect(entries.map((e) => [e.name, e.method, e.unixMode])).toEqual([
      ['manifest.json', 8, 0o100000],
      ['assets/été.png', 0, 0o100000],
      ['assets/empty.txt', 0, 0o100000],
    ])
    expect(dec.decode(readZipEntry(zip, entries[0]!))).toBe('{"a":1}'.repeat(50))
    expect([...readZipEntry(zip, entries[1]!)]).toEqual([...random])
    expect(readZipEntry(zip, entries[2]!).length).toBe(0)
  })
})

describe('ouaf pack (command)', () => {
  it('writes <folder>.ouaf next to the folder by default; exit 0', async () => {
    const dir = await folder({ 'filter.js': filterJs() })
    const r = await cli('pack', dir)
    expect(r.code).toBe(EXIT.OK)
    expect(r.out).toContain(`Wrote ${dir}.ouaf: 1 file`)
    expect((await cli('validate', `${dir}.ouaf`)).code).toBe(EXIT.OK)
  })

  it('-o creates the parent folders and replaces an existing file', async () => {
    const out = join(await temp(), 'dist', 'x.ouaf')
    const dir = await folder({ 'filter.js': filterJs() })
    expect((await cli('pack', dir, '-o', out)).code).toBe(EXIT.OK)
    await writeFile(out, 'old')
    expect((await cli('pack', dir, '-o', out)).code).toBe(EXIT.OK)
    expect((await readFile(out)).subarray(0, 2).toString()).toBe('PK')
  })

  it('exit 1 and nothing written when the filter is invalid, or with --strict and a warning', async () => {
    const bad = await folder({ 'filter.js': filterJs(`layers: [{ type: 'text', text: 'hi', anchor: 'forehaed' }]`) })
    const r = await cli('pack', bad)
    expect(r.code).toBe(EXIT.FAILED)
    expect(r.out).toContain('filter.js /layers/0/anchor — error [unknown-anchor]')
    expect(r.out).toContain('was not written')
    await expect(stat(`${bad}.ouaf`)).rejects.toThrow()

    const warned = await folder({ 'filter.js': filterJs(), 'assets/unused.json': '{}' })
    expect((await cli('pack', warned)).code).toBe(EXIT.OK)
    await rm(`${warned}.ouaf`)
    expect((await cli('pack', '--strict', warned)).code).toBe(EXIT.FAILED)
    await expect(stat(`${warned}.ouaf`)).rejects.toThrow()
  })

  it('--json prints the report with the output and the package files', async () => {
    const out = join(await temp(), 'x.ouaf')
    const r = await cli('pack', authoring, '-o', out, '--json')
    expect(r.code).toBe(EXIT.OK)
    const json = JSON.parse(r.out) as Record<string, unknown>
    expect(json).toMatchObject({ format: 1, ok: true, output: out, entry: 'filter.ts', packageFiles: ['manifest.json', 'script.js', 'assets/star.png'] })
  })

  it('exit 2 for usage errors', async () => {
    expect((await cli('pack')).code).toBe(EXIT.USAGE)
    expect((await cli('pack', 'a', 'b')).code).toBe(EXIT.USAGE)
    expect((await cli('pack', join(fixtures, 'nope'))).code).toBe(EXIT.USAGE)
    const dir = await folder({ 'filter.js': filterJs() })
    expect((await cli('pack', dir, '-o', join(dir, 'x.zip'))).code).toBe(EXIT.USAGE)
    const r = await cli('pack', dir, '-o', join(dir, 'assets', 'x.ouaf'))
    expect(r.code).toBe(EXIT.USAGE)
    expect(r.err).toContain("inside the filter's assets/ folder")
    expect((await cli('pack', `${dir}/filter.js`)).code).toBe(EXIT.USAGE)
    expect((await cli('pack', '--help')).out).toContain('Usage: ouaf pack <folder>')
  })
})
